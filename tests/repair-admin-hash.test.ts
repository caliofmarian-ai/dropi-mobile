/**
 * Tests for scripts/repair-admin-hash.ts
 *
 * Covers:
 *  - account not found → returns "not_found"
 *  - missing hash (null) → repaired, DB updated
 *  - invalid bcrypt format (plain text / garbage) → repaired, DB updated
 *  - hash mismatch (old password) → repaired, DB updated
 *  - valid hash that matches → returns "ok", no DB update
 *  - repaired hash verifies correctly against ADMIN_PASSWORD
 *  - secrets (password, hash) never written to any log channel
 *  - validateRepairEnv throws on missing required vars
 *  - isValidBcryptHash recognises valid and invalid patterns
 */

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import bcrypt from "bcryptjs";
import {
  repairAdminHash,
  validateRepairEnv,
  isValidBcryptHash,
  type RepairDb,
  type RepairInput,
} from "../scripts/repair-admin-hash";

// ===== MOCK DB FACTORY =====

function createMockDb(
  existingRow: { id: number; passwordHash: string | null } | null = null,
): {
  db: RepairDb;
  getUpdatedValues: () => Record<string, unknown> | undefined;
  updateCallCount: () => number;
} {
  let updatedValues: Record<string, unknown> | undefined = undefined;
  let updateCallCount = 0;

  const db: RepairDb = {
    select: vi.fn().mockReturnValue({
      from: vi.fn().mockReturnValue({
        where: vi.fn().mockReturnValue({
          limit: vi.fn().mockResolvedValue(existingRow ? [existingRow] : []),
        }),
      }),
    }),
    update: vi.fn().mockImplementation(() => ({
      set: vi.fn().mockImplementation((data: Record<string, unknown>) => {
        updatedValues = data;
        updateCallCount++;
        return {
          where: vi.fn().mockResolvedValue({ affectedRows: 1 }),
        };
      }),
    })),
  };

  return {
    db,
    getUpdatedValues: () => updatedValues,
    updateCallCount: () => updateCallCount,
  };
}

const VALID_PASSWORD = "SecureAdmin1";
const VALID_INPUT: RepairInput = {
  email: "admin@example.com",
  password: VALID_PASSWORD,
};

// ===== isValidBcryptHash =====

describe("isValidBcryptHash", () => {
  it("returns true for a valid $2a$ bcrypt hash", () => {
    // A real bcrypt hash generated by bcryptjs
    const hash = "$2a$12$LQv3c1yqBWVHxkd0LHAkCOYz6TtxMQJqhN8/uw0/.6oKx1e4BWTKS";
    expect(isValidBcryptHash(hash)).toBe(true);
  });

  it("returns true for a valid $2b$ bcrypt hash", () => {
    const hash = "$2b$12$LQv3c1yqBWVHxkd0LHAkCOYz6TtxMQJqhN8/uw0/.6oKx1e4BWTKS";
    expect(isValidBcryptHash(hash)).toBe(true);
  });

  it("returns false for a plain-text password", () => {
    expect(isValidBcryptHash("SecureAdmin1")).toBe(false);
  });

  it("returns false for an empty string", () => {
    expect(isValidBcryptHash("")).toBe(false);
  });

  it("returns false for null", () => {
    expect(isValidBcryptHash(null)).toBe(false);
  });

  it("returns false for undefined", () => {
    expect(isValidBcryptHash(undefined)).toBe(false);
  });

  it("returns false for a truncated hash", () => {
    expect(isValidBcryptHash("$2a$12$LQv3c1yq")).toBe(false);
  });
});

// ===== repairAdminHash — account not found =====

describe("repairAdminHash — account not found", () => {
  it("returns status 'not_found' when no row exists", async () => {
    const { db } = createMockDb(null);
    const result = await repairAdminHash(db, VALID_INPUT);
    expect(result.status).toBe("not_found");
    expect(result.email).toBe("admin@example.com");
  });

  it("does not call update when account is not found", async () => {
    const { db, updateCallCount } = createMockDb(null);
    await repairAdminHash(db, VALID_INPUT);
    expect(updateCallCount()).toBe(0);
  });

  it("normalises email to lowercase in the result", async () => {
    const { db } = createMockDb(null);
    const result = await repairAdminHash(db, { ...VALID_INPUT, email: "ADMIN@Example.COM" });
    expect(result.email).toBe("admin@example.com");
  });
});

// ===== repairAdminHash — missing hash =====

describe("repairAdminHash — missing passwordHash", () => {
  it("returns status 'repaired' when passwordHash is null", async () => {
    const { db } = createMockDb({ id: 1, passwordHash: null });
    const result = await repairAdminHash(db, VALID_INPUT);
    expect(result.status).toBe("repaired");
    if (result.status === "repaired") {
      expect(result.reason).toBe("missing_hash");
    }
  });

  it("calls update exactly once when hash is null", async () => {
    const { db, updateCallCount } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);
    expect(updateCallCount()).toBe(1);
  });

  it("stores a valid bcrypt hash in the update call", async () => {
    const { db, getUpdatedValues } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);
    const updated = getUpdatedValues();
    expect(updated).toBeDefined();
    expect(isValidBcryptHash(updated!.passwordHash)).toBe(true);
  });

  it("the new hash verifies correctly against the supplied password", async () => {
    const { db, getUpdatedValues } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);
    const updated = getUpdatedValues();
    const matches = await bcrypt.compare(VALID_PASSWORD, updated!.passwordHash as string);
    expect(matches).toBe(true);
  });
});

