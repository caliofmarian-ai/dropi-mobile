// ===== repairAdminHash — hash mismatch =====

describe("repairAdminHash — hash mismatch (wrong password)", () => {
  it("returns status 'repaired' when bcrypt.compare returns false", async () => {
    const staleHash = await bcrypt.hash("OldPassword99", 12);
    const { db } = createMockDb({ id: 1, passwordHash: staleHash });
    const result = await repairAdminHash(db, VALID_INPUT);
    expect(result.status).toBe("repaired");
    if (result.status === "repaired") {
      expect(result.reason).toBe("hash_mismatch");
    }
  });

  it("calls update exactly once for hash mismatch", async () => {
    const staleHash = await bcrypt.hash("OldPassword99", 12);
    const { db, updateCallCount } = createMockDb({ id: 1, passwordHash: staleHash });
    await repairAdminHash(db, VALID_INPUT);
    expect(updateCallCount()).toBe(1);
  });

  it("the new hash verifies correctly after mismatch repair", async () => {
    const staleHash = await bcrypt.hash("OldPassword99", 12);
    const { db, getUpdatedValues } = createMockDb({ id: 1, passwordHash: staleHash });
    await repairAdminHash(db, VALID_INPUT);
    const updated = getUpdatedValues();
    const matches = await bcrypt.compare(VALID_PASSWORD, updated!.passwordHash as string);
    expect(matches).toBe(true);
  });
});

// ===== repairAdminHash — valid hash (no change) =====

describe("repairAdminHash — valid hash matches password", () => {
  it("returns status 'ok' when hash is valid and matches", async () => {
    const correctHash = await bcrypt.hash(VALID_PASSWORD, 12);
    const { db } = createMockDb({ id: 1, passwordHash: correctHash });
    const result = await repairAdminHash(db, VALID_INPUT);
    expect(result.status).toBe("ok");
    expect(result.email).toBe("admin@example.com");
  });

  it("does NOT call update when hash is already correct", async () => {
    const correctHash = await bcrypt.hash(VALID_PASSWORD, 12);
    const { db, updateCallCount } = createMockDb({ id: 1, passwordHash: correctHash });
    await repairAdminHash(db, VALID_INPUT);
    expect(updateCallCount()).toBe(0);
  });
});

// ===== SECRETS NOT LOGGED =====

describe("repairAdminHash — secrets not logged", () => {
  it("does not write the password to any console channel", async () => {
    const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
    const warnSpy = vi.spyOn(console, "warn").mockImplementation(() => {});
    const errorSpy = vi.spyOn(console, "error").mockImplementation(() => {});

    const { db } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);

    const allLogged = [
      ...logSpy.mock.calls,
      ...warnSpy.mock.calls,
      ...errorSpy.mock.calls,
    ]
      .flat()
      .map(String);

    for (const line of allLogged) {
      expect(line).not.toContain(VALID_PASSWORD);
    }

    logSpy.mockRestore();
    warnSpy.mockRestore();
    errorSpy.mockRestore();
  });

  it("does not write the new hash to any console channel", async () => {
    const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
    const warnSpy = vi.spyOn(console, "warn").mockImplementation(() => {});
    const errorSpy = vi.spyOn(console, "error").mockImplementation(() => {});

    const { db, getUpdatedValues } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);

    const newHash = (getUpdatedValues() as Record<string, unknown>).passwordHash as string;

    const allLogged = [
      ...logSpy.mock.calls,
      ...warnSpy.mock.calls,
      ...errorSpy.mock.calls,
    ]
      .flat()
      .map(String);

    for (const line of allLogged) {
      expect(line).not.toContain(newHash);
    }

    logSpy.mockRestore();
    warnSpy.mockRestore();
    errorSpy.mockRestore();
  });
});

// ===== ONLY THE TARGET ROW IS EVER MODIFIED =====

describe("repairAdminHash — only target row modified", () => {
  it("update is called with only passwordHash — no email, role, or status field", async () => {
    const { db, getUpdatedValues } = createMockDb({ id: 1, passwordHash: null });
    await repairAdminHash(db, VALID_INPUT);
    const updated = getUpdatedValues();
    expect(updated).toBeDefined();
    // Only passwordHash should be set — no other field
    expect(Object.keys(updated!)).toEqual(["passwordHash"]);
    expect(updated!["email"]).toBeUndefined();
    expect(updated!["dropiRole"]).toBeUndefined();
    expect(updated!["isActive"]).toBeUndefined();
    expect(updated!["isVerified"]).toBeUndefined();
    expect(updated!["emailVerified"]).toBeUndefined();
    expect(updated!["role"]).toBeUndefined();
  });

  it("update is not called for a user with a different id when no hash match is needed", async () => {
    // Simulate a correct hash for user id=99 — no update should occur
    const correctHash = await bcrypt.hash(VALID_PASSWORD, 12);
    const { db, updateCallCount } = createMockDb({ id: 99, passwordHash: correctHash });
    await repairAdminHash(db, VALID_INPUT);
    // User id=99 is fine — no other row should be touched
    expect(updateCallCount()).toBe(0);
  });

  it("update is called exactly once even when hash is malformed (not for every user)", async () => {
    const { db, updateCallCount } = createMockDb({ id: 42, passwordHash: "not-a-hash" });
    await repairAdminHash(db, VALID_INPUT);
    // Exactly one update for the one target user
    expect(updateCallCount()).toBe(1);
  });
});

// ===== validateRepairEnv =====

describe("validateRepairEnv — environment validation", () => {
  const originalEnv = { ...process.env };

  beforeEach(() => {
    process.env.DATABASE_URL = "mysql://host:3306/db";
    process.env.ADMIN_EMAIL = "admin@example.com";
    process.env.ADMIN_PASSWORD = "SecureAdmin1";
  });

  afterEach(() => {
    for (const key of ["DATABASE_URL", "ADMIN_EMAIL", "ADMIN_PASSWORD"]) {
      if (originalEnv[key] !== undefined) {
        process.env[key] = originalEnv[key];
      } else {
        delete process.env[key];
      }
    }
  });

  it("throws when DATABASE_URL is missing", () => {
    delete process.env.DATABASE_URL;
    expect(() => validateRepairEnv()).toThrow("DATABASE_URL environment variable is required");
  });

  it("throws when ADMIN_EMAIL is missing", () => {
    delete process.env.ADMIN_EMAIL;
    expect(() => validateRepairEnv()).toThrow("ADMIN_EMAIL environment variable is required");
  });

  it("throws when ADMIN_PASSWORD is missing", () => {
    delete process.env.ADMIN_PASSWORD;
    expect(() => validateRepairEnv()).toThrow("ADMIN_PASSWORD environment variable is required");
  });

  it("returns all fields when environment is valid", () => {
    const env = validateRepairEnv();
    expect(env.databaseUrl).toBe("mysql://host:3306/db");
    expect(env.email).toBe("admin@example.com");
    expect(env.password).toBe("SecureAdmin1");
  });
});
